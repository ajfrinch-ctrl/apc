/**
 * আজকের (Asia/Dhaka) নির্ধারিত পরামর্শ। দিন-সংখ্যা % তালিকা-দৈর্ঘ্য, তাই আগামীকাল
 * সূচক সবসময় এগিয়ে যায়। কোনো ব্যতিক্রমে প্রথম লাইনটি ফলব্যাক।
 * @param {number} [now] epoch millis (ডিফল্ট: বর্তমান সময়)
 * @returns {string}
 */
export function pickTeacherAdvice(now = Date.now()) {
  const list = TEACHER_DAILY_ADVICE;
  try {
    const day = quoteDayNumber(quoteDateKey(now));
    const index = ((day % list.length) + list.length) % list.length;
    return list[index] || list[0];
  } catch {
    return list[0];
  }
}

